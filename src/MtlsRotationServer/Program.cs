using Microsoft.AspNetCore.Authentication.Certificate;
using Microsoft.AspNetCore.Server.Kestrel.Https;
using System.Security.Claims;
using System.Security.Cryptography.X509Certificates;

var builder = WebApplication.CreateBuilder(args);

// Host DI logging (ILogger<T> in controllers, etc.) comes from WebApplication.CreateBuilder.
builder.Services.AddControllers();

// Extra logger for startup cert loading + Kestrel ClientCertificateValidation.
// The TLS callback runs before the HTTP pipeline / request DI scope exist.
// Exception middleware also cannot catch TLS rejects (connection never becomes an HTTP request).
var certsLogger = LoggerFactory
    .Create(b => b
        .AddConfiguration(builder.Configuration.GetSection("Logging"))
        .AddConsole())
    .CreateLogger("MtlsRotationServer.Certificates");

// Certs are generated by scripts/generate-certs.ps1 and copied to output.
// Server keeps only public material (.crt): public key + metadata, no private key, no password.
// Project choices for this demo:
// - Resources/CACerts/*.crt: custom trust anchors (CustomRootTrust). Any count; demo ships two for CA rotation.
//   You could instead use the system trust store or a single CA.
// - Resources/ClientCerts/*.crt: allowlist by thumbprint. Any count; demo ships two for client cert rotation.
//   Identity (CN / clientId, …) comes from the presented cert after a match.
// Expired files in either folder are skipped at startup (warning logged).

var caCertsDir = Path.Combine(AppContext.BaseDirectory, "Resources", "CACerts");
var clientCertsDir = Path.Combine(AppContext.BaseDirectory, "Resources", "ClientCerts");

var configuredCACerts = LoadNonExpiredCertificates(caCertsDir, certsLogger).ToList();
if (configuredCACerts.Count == 0)
{
    throw new InvalidOperationException(
        "No usable CA certificates were found (missing or all expired). Run .\\scripts\\generate-certs.ps1 first " +
        $"(expected: {caCertsDir}\\*.crt).");
}

var trustedConfiguredClientCertificatesThumbprints = LoadNonExpiredCertificates(clientCertsDir, certsLogger)
    .Select(c => c.Thumbprint)
    .ToHashSet(StringComparer.OrdinalIgnoreCase);

if (trustedConfiguredClientCertificatesThumbprints.Count == 0)
{
    throw new InvalidOperationException(
        "No usable client certificates were found (missing or all expired). Run .\\scripts\\generate-certs.ps1 first " +
        $"(expected: {clientCertsDir}\\*.crt).");
}

builder.WebHost.ConfigureKestrel(options =>
{
    options.ConfigureHttpsDefaults(httpsOptions =>
    {
        // Require client certificate for all HTTPS endpoints in the API (mTLS).
        // This ignores [Authorize] attributes on endpoints:
        // Kestrel will reject the connection if the client doesn't present a valid certificate.
        httpsOptions.ClientCertificateMode = ClientCertificateMode.RequireCertificate;

        // TLS gate: thumbprint allowlist + chain → any configured CA (also enforces NotTimeValid).
        // Log each reject reason — typical enterprise practice for mTLS diagnostics / monitoring.
        httpsOptions.ClientCertificateValidation = (certificateFromRequest, _, _) =>
        {
            if (certificateFromRequest is null)
            {
                if (certsLogger.IsEnabled(LogLevel.Warning))
                {
                    certsLogger.LogWarning("Rejecting mTLS connection: client certificate was not presented.");
                }

                return false;
            }

            if (certificateFromRequest is not X509Certificate2 clientCertFromRequest)
            {
                clientCertFromRequest = X509CertificateLoader.LoadCertificate(certificateFromRequest.GetRawCertData());
            }

            // Validate the client certificate against whitelist of thumbprints (trusted client certs).
            if (!trustedConfiguredClientCertificatesThumbprints.Contains(clientCertFromRequest.Thumbprint))
            {
                if (certsLogger.IsEnabled(LogLevel.Warning))
                {
                    certsLogger.LogWarning(
                        "Rejecting client certificate not on allowlist {Thumbprint} (Subject={Subject})",
                        clientCertFromRequest.Thumbprint,
                        clientCertFromRequest.Subject);
                }

                return false;
            }

            // Chain must end at one of our configured CAs (supports CA rotation / grace).
            using var chain = new X509Chain();
            chain.ChainPolicy.TrustMode = X509ChainTrustMode.CustomRootTrust;
            foreach (var ca in configuredCACerts)
            {
                chain.ChainPolicy.CustomTrustStore.Add(ca);
            }

            // No CRL/OCSP: with thumbprint pinning we revoke by removing the cert from the allowlist.
            chain.ChainPolicy.RevocationMode = X509RevocationMode.NoCheck;

            if (!chain.Build(clientCertFromRequest))
            {
                if (certsLogger.IsEnabled(LogLevel.Warning))
                {
                    var status = string.Join("; ", chain.ChainStatus.Select(s => $"{s.Status}: {s.StatusInformation.Trim()}"));
                    certsLogger.LogWarning(
                        "Rejecting client certificate {Thumbprint}: chain validation failed ({ChainStatus})",
                        clientCertFromRequest.Thumbprint,
                        status);
                }

                return false;
            }

            return true;
        };
    });
});

// Map the client certificate into ASP.NET identity (HttpContext.User / claims)
// so controllers can read clientId, thumbprint, etc. from User.
builder.Services
    .AddAuthentication(CertificateAuthenticationDefaults.AuthenticationScheme)
    .AddCertificate(options =>
    {
        // Minimal check here (chain to our CAs only) — allowlist and revoke policy already enforced in Kestrel above.
        options.AllowedCertificateTypes = CertificateTypes.Chained;
        options.RevocationMode = X509RevocationMode.NoCheck;
        options.ChainTrustValidationMode = X509ChainTrustMode.CustomRootTrust;
        foreach (var ca in configuredCACerts)
        {
            options.CustomTrustStore.Add(ca);
        }

        options.Events = new CertificateAuthenticationEvents
        {
            OnCertificateValidated = context =>
            {
                var cert = context.ClientCertificate;

                // Identity comes from the presented cert after mTLS already allowed it.
                var clientId = cert.GetNameInfo(X509NameType.SimpleName, forIssuer: false);
                if (string.IsNullOrWhiteSpace(clientId))
                {
                    context.Fail("Client certificate has no CN / simple name.");
                    return Task.CompletedTask;
                }

                var claims = new[]
                {
                    new Claim(ClaimTypes.NameIdentifier, clientId),
                    new Claim("client_id", clientId),
                    new Claim("cert_thumbprint", cert.Thumbprint),
                    new Claim("not_after", cert.NotAfter.ToUniversalTime().ToString("O"))
                };

                context.Principal = new ClaimsPrincipal(
                    new ClaimsIdentity(claims, CertificateAuthenticationDefaults.AuthenticationScheme));
                context.Success();
                return Task.CompletedTask;
            }
        };
    });

builder.Services.AddAuthorization();

var app = builder.Build();

app.UseAuthentication();
app.UseAuthorization();

app.MapControllers();

app.Run();

static IEnumerable<X509Certificate2> LoadNonExpiredCertificates(string directory, ILogger logger)
{
    if (!Directory.Exists(directory))
    {
        throw new InvalidOperationException(
            $"Certificate directory '{directory}' does not exist. Run .\\scripts\\generate-certs.ps1 first.");
    }

    foreach (var path in Directory.GetFiles(directory, "*.crt"))
    {
        var certificate = X509CertificateLoader.LoadCertificateFromFile(path);
        if (certificate.NotAfter <= DateTime.UtcNow)
        {
            if (logger.IsEnabled(LogLevel.Warning))
            {
                // This will help tidying up the certificates after they are expired.
                logger.LogWarning(
                    "Skipping expired certificate {Path} (Subject={Subject}, NotAfter={NotAfter:o})",
                    path,
                    certificate.Subject,
                    certificate.NotAfter);
            }

            continue;
        }

        yield return certificate;
    }
}